use tiendita;

-- Tablas
CREATE TABLE Departamentos(
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(30)
);

CREATE TABLE Empleados(
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    apellido VARCHAR(50) NOT NULL,
    genero VARCHAR(5) NOT NULL,
    edad INT,
    id_dpto INT,
    CONSTRAINT fk_departamento
    FOREIGN KEY (id_dpto)
    REFERENCES Departamentos (id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);


CREATE TABLE Spa(
    id INT AUTO_INCREMENT PRIMARY KEY,
    fecha DATE,
    id_empleado INT,
    CONSTRAINT fk_empleado_spa
    FOREIGN KEY (id_empleado)
    REFERENCES Empleados (id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);

CREATE TABLE Masaje(
    id INT AUTO_INCREMENT PRIMARY KEY,
    fecha DATE,
    id_empleado INT,
    CONSTRAINT fk_empleado_masaje
    FOREIGN KEY (id_empleado)
    REFERENCES Empleados (id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);
 

-- Constraints para no permitir que un empleado pueda ir dos veces en la misma fecha a un mismo servicio

ALTER TABLE Spa
ADD CONSTRAINT uq_spa_empleado_fecha
UNIQUE (id_empleado, fecha);

ALTER TABLE Masaje
ADD CONSTRAINT uq_masaje_empleado_fecha
UNIQUE (id_empleado, fecha);


